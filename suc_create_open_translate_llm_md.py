import requests
import time

file_path = '/content/The Three Musketeers.md'

# Read the large markdown file
with open(file_path, 'r', encoding='utf-8') as f:
    original_markdown_content = f.read()

# Define the server URL
LLAMA_SERVER_URL = "http://localhost:8000/completion"

def translate_chunk(text_chunk, target_language="Arabic"):
    prompt = f"Translate the following text into {target_language}:\n\n{text_chunk}"
    payload = {
        "prompt": prompt,
        "n_predict": 1024, # Maximum number of tokens to generate
        "temperature": 0.1,
        "stop": ["\n\n", "<|im_end|>", "\n---"], # Stop sequences for generation
        "stream": False
    }

    try:
        response = requests.post(LLAMA_SERVER_URL, json=payload, timeout=300) # 5 minutes timeout
        response.raise_for_status() # Raise an exception for HTTP errors
        result = response.json()
        if 'content' in result['choices'][0]:
            return result['choices'][0]['content'].strip()
        else:
            print(f"Warning: No content in response for chunk: {text_chunk[:50]}...")
            return ""
    except requests.exceptions.RequestException as e:
        print(f"Error communicating with llama.cpp server: {e}")
        return ""

# Split the content into chunks to handle large files
# Adjust chunk_size based on model context window and performance
chunk_size = 1500 # characters, not tokens. This is an approximation.
text_chunks = [original_markdown_content[i:i + chunk_size] for i in range(0, len(original_markdown_content), chunk_size)]

translated_chunks = []
print(f"Translating {len(text_chunks)} chunks...")

for i, chunk in enumerate(text_chunks):
    print(f"Translating chunk {i+1}/{len(text_chunks)}...")
    translated_text = translate_chunk(chunk)
    translated_chunks.append(translated_text)
    time.sleep(1) # Small delay to avoid overwhelming the server

full_translated_content = "\n\n".join(translated_chunks)

# Save the translated content to a new markdown file
output_file_path = '/content/The Three Musketeers_ar.md'
with open(output_file_path, 'w', encoding='utf-8') as f:
    f.write(full_translated_content)

print(f"Translation complete! Saved to {output_file_path}")

# Display the first part of the translated content as markdown
from IPython.display import Markdown
display(Markdown(full_translated_content[:2000] + "\n\n... (truncated for display) ..."))

